# BUG-01: Поиск по невалидным символам показывает товары вместо "Ничего не найдено"

## Описание
При вводе в поле поиска невалидных символов (спецсимволы, случайные наборы букв) приложение показывает товары из разных категорий, хотя должно показывать сообщение «Ничего не найдено». Поведение непредсказуемое: результат зависит от типа символов и их количества.

## Шаги воспроизведения
1. Открыть приложение Самокат.
2. Открыть поле поиска.
3. Ввести `!@#$%^&*` → нажать «Найти».
4. Очистить поиск.
5. Ввести `dd'd'@` → нажать «Найти».
6. Очистить поиск.
7. Ввести `gg'd'@` → нажать «Найти».
8. Очистить поиск.
9. Ввести `['d'@` → нажать «Найти».

## Ожидаемый результат
Во всех случаях — сообщение «Ничего не найдено», список товаров пуст.

## Фактический результат
| Запрос | Что показывает |
|---|---|
| `!@#$%^&*` | Все товары подряд (попкорн, крекеры, ириски) |
| `dd'd'@` | Овощи (шампиньоны, шпинат, паштет, морковь, грибы, редис) |
| `gg'd'@` | Мясо (варёная колбаса, сосиски) |
| `ffd'@` | Ароматические свечи |
| `['d'@` | Косметика (скрабы, шампуни, маски) |

## Дополнительные наблюдения
- Пустой запрос → «Ничего не найдено» (правильно).
- Пробелы → «Ничего не найдено» (правильно).
- `!молоко` → находит молоко (правильно).
- SQL-инъекции (`' OR '1'='1`) → «Ничего не найдено» (правильно).
- Кириллица (`шш'd'@`) → всегда одно и то же (каши, кофе).
- Латиница — зависит от символов и длины.

## Влияние
- Непредсказуемое поведение поиска.
- Пользователь вводит мусор — получает реальные товары.
- Может привести к покупке не того товара.
- Подрывает доверие к поиску.

